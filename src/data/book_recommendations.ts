// Helper function to get books by genre
export const getBooksByGenre = (genre: string): BookRecommendation[] => {
  return bookRecommendations.filter(book => book.genre === genre);
};

// Helper function to get all unique genres
export const getAllGenres = (): string[] => {
  return [...new Set(bookRecommendations.map(book => book.genre))];
};

// Helper function to get a random book
export const getRandomBook = (): BookRecommendation => {
  return bookRecommendations[Math.floor(Math.random() * bookRecommendations.length)];
};

// Helper function to search books
export const searchBooks = (query: string): BookRecommendation[] => {
  const lowerQuery = query.toLowerCase();
  return bookRecommendations.filter(book =>
    book.title.toLowerCase().includes(lowerQuery) ||
    book.author.toLowerCase().includes(lowerQuery) ||
    book.genre.toLowerCase().includes(lowerQuery) ||
    book.description.toLowerCase().includes(lowerQuery)
  );
};

export default bookRecommendations;
