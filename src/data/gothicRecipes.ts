// ==================== HELPER FUNCTIONS ====================

export const getRecipesByCategory = (category: RecipeCategory): GothicRecipe[] => {
  return gothicRecipes.filter(r => r.category === category);
};

export const getRecipesByCulture = (culture: CulturalOrigin): GothicRecipe[] => {
  return gothicRecipes.filter(r => r.culturalOrigin === culture);
};

export const getRecipesBySpoonLevel = (maxSpoons: SpoonLevel): GothicRecipe[] => {
  return gothicRecipes.filter(r => r.spoonLevel <= maxSpoons);
};

export const getQuickRecipes = (maxMinutes: number = 30): GothicRecipe[] => {
  return gothicRecipes.filter(r => (r.prepTime + r.cookTime) <= maxMinutes);
};

export const getRecipesByDiet = (diet: DietaryTag): GothicRecipe[] => {
  return gothicRecipes.filter(r => r.dietaryTags.includes(diet));
};

export const searchRecipes = (query: string): GothicRecipe[] => {
  const lowerQuery = query.toLowerCase();
  return gothicRecipes.filter(r =>
    r.name.toLowerCase().includes(lowerQuery) ||
    r.gothicName.toLowerCase().includes(lowerQuery) ||
    r.description.toLowerCase().includes(lowerQuery) ||
    r.ingredients.some(i => i.name.toLowerCase().includes(lowerQuery))
  );
};

export const getTotalTime = (recipe: GothicRecipe): number => {
  return recipe.prepTime + recipe.cookTime;
};

export const formatTime = (minutes: number): string => {
  if (minutes < 60) return `${minutes} min`;
  const hours = Math.floor(minutes / 60);
  const mins = minutes % 60;
  return mins > 0 ? `${hours}h ${mins}m` : `${hours}h`;
};

export const getRandomRecipe = (): GothicRecipe => {
  return gothicRecipes[Math.floor(Math.random() * gothicRecipes.length)];
};

export const getRecipeById = (id: string): GothicRecipe | undefined => {
  return gothicRecipes.find(r => r.id === id);
};

