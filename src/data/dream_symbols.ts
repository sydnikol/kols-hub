// Helper functions for working with dream symbols
export const getSymbolsByCategory = (category: DreamSymbol['category']): DreamSymbol[] => {
  return dreamSymbols.filter(symbol => symbol.category === category);
};

export const searchSymbols = (query: string): DreamSymbol[] => {
  const lowerQuery = query.toLowerCase();
  return dreamSymbols.filter(symbol =>
    symbol.name.toLowerCase().includes(lowerQuery) ||
    symbol.meanings.some(m => m.toLowerCase().includes(lowerQuery)) ||
    symbol.contexts.some(c => c.toLowerCase().includes(lowerQuery))
  );
};

export const getSymbolById = (id: string): DreamSymbol | undefined => {
  return dreamSymbols.find(symbol => symbol.id === id);
};

