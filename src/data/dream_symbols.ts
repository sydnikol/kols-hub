// Auto-detect symbols from dream text
export const detectSymbolsInText = (text: string): string[] => {
  const lowerText = text.toLowerCase();
  const detectedSymbols: Set<string> = new Set();

  Object.entries(symbolKeywords).forEach(([symbolId, keywords]) => {
    for (const keyword of keywords) {
      // Use word boundary matching
      const regex = new RegExp(`\\b${keyword}\\b`, 'i');
      if (regex.test(lowerText)) {
        detectedSymbols.add(symbolId);
        break;
      }
    }
  });

  return Array.from(detectedSymbols);
};

export default dreamSymbols;
